const DICTIONARIES = { en, fr };

let current = FALLBACK;
let pluralRules = new Intl.PluralRules(FALLBACK);

/** Picks the language from the browser preferences (I-2). */
export function detectLanguage() {
  const preferences = navigator.languages?.length ? navigator.languages : [navigator.language || FALLBACK];
  for (const tag of preferences) {
    const lower = String(tag).toLowerCase();
    if (lower.startsWith('fr')) return 'fr';
    if (lower.startsWith('en')) return 'en';
  }
  return FALLBACK;
}

/** Returns the saved preference when valid, otherwise the detected language (I-3). */
export function resolveLanguage(preference) {
  return LANGUAGES.includes(preference) ? preference : detectLanguage();
}

/** Sets the current language and updates <html lang> (I-4). */
export function setLanguage(language) {
  current = LANGUAGES.includes(language) ? language : FALLBACK;
  pluralRules = new Intl.PluralRules(current);
  document.documentElement.lang = current;
}

/** Returns the current language code. */
export function getLanguage() {
  return current;
}

/** True when a translation exists for the key. */
export function has(key) {
  return key in DICTIONARIES[current] || key in DICTIONARIES[FALLBACK];
}

/**
 * Translates a key and fills named parameters, for example t('import.done', { playlists: '2 playlists' }) (I-6).
 * Returns `fallback` (or the key itself) when no translation exists.
 */
export function t(key, params = {}, fallback = key) {
  const template = DICTIONARIES[current][key] ?? DICTIONARIES[FALLBACK][key] ?? fallback;
  return String(template).replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

/** Translates a key with a plural form chosen from `count` (keys end with .one, .other, …). */
export function tn(key, count, params = {}) {
  const form = pluralRules.select(count);
  const pluralKey = has(`${key}.${form}`) ? `${key}.${form}` : `${key}.other`;
  return t(pluralKey, { count, ...params });
}
